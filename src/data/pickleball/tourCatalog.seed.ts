import type { PaddleProfile, PlayBias, PaddleShape, PaddleCore, PaddleFace, FaceTexture } from "@/types/pickleball";

/**
 * Local tour-level paddle catalog seed.
 *
 * There is no reliable public API for “paddles used on tour.” This seed is the
 * expandable source of truth for popular PPA / MLP / serious-league models that
 * sit alongside Pickleball Effect lab measurements in paddles.snapshot.json.
 *
 * Specs are manufacturer-catalog / coaching-estimate — not lab percentiles.
 * Add new paddles here; lab-backed IDs in the snapshot always win on merge.
 */

type SeedInput = {
  id: string;
  brand: string;
  name: string;
  shape?: PaddleShape;
  core?: PaddleCore;
  face?: PaddleFace;
  texture?: FaceTexture;
  weightOz: number;
  thicknessMm: number;
  swingweight?: number | null;
  twistWeight?: number | null;
  balanceMm?: number | null;
  bias: PlayBias;
  power: number;
  control: number;
  spin: number;
  pop: number;
  sweetSpot: number;
  balance?: number;
  gripCircumferenceIn?: number;
  gripLengthIn?: number;
  edgeGuard?: PaddleProfile["edgeGuard"];
  feel: string;
  uniqueTrait: string;
  bestFor: string;
  tourPresence: string;
  year?: number;
  approval?: string;
};

function seed(p: SeedInput): PaddleProfile {
  return {
    id: p.id,
    brand: p.brand,
    name: p.name,
    shape: p.shape ?? "elongated",
    core: p.core ?? "polymer",
    face: p.face ?? "raw-carbon",
    texture: p.texture ?? "raw",
    weightOz: p.weightOz,
    thicknessMm: p.thicknessMm,
    swingweight: p.swingweight ?? null,
    twistWeight: p.twistWeight ?? null,
    balanceMm: p.balanceMm ?? null,
    balance: p.balance ?? 0.1,
    gripCircumferenceIn: p.gripCircumferenceIn ?? 4.25,
    gripLengthIn: p.gripLengthIn ?? 5.5,
    edgeGuard: p.edgeGuard ?? "foam-injected",
    power: p.power,
    control: p.control,
    spin: p.spin,
    pop: p.pop,
    sweetSpot: p.sweetSpot,
    bias: p.bias,
    feel: p.feel,
    uniqueTrait: p.uniqueTrait,
    bestFor: p.bestFor,
    notes:
      "Tour-seed catalog entry. Specs are manufacturer / coaching estimates for compare — not Pickleball Effect lab percentiles. Prefer lab-measured rows when both exist.",
    year: p.year ?? null,
    approval: p.approval ?? "USAP",
    measured: null,
    specsProvenance: "manufacturer-catalog",
    imageProvenance: null,
    catalogTier: "tour-seed",
    tourPresence: p.tourPresence,
  };
}

